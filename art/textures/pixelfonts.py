"""Bitmap fonts copied from the game's own sign lettering, for signs drawn in pixel type.

Each glyph is (rows, below): rows top to bottom ("#" = ink), below = how many of them hang under the
baseline. Glyphs are drawn bottom-aligned on a baseline, so accented capitals simply have more rows.
Letters the original sign doesn't have (accents, q, D, O, G, ...) are drawn by hand in the same style
and marked "drawn".
"""


def _accent(base, mark, gap=1):
    """base glyph with mark rows on top, separated by gap empty rows."""
    rows, below = base
    w = len(rows[0])
    mark = [m.ljust(w, ".")[:w] for m in mark]
    return (mark + ["." * w] * gap + list(rows), below)


def _below(base, mark):
    rows, below = base
    w = len(rows[0])
    return (list(rows) + [m.ljust(w, ".")[:w] for m in mark], below + len(mark))


